#!/usr/bin/env python3
"""Generate Plateau's readonly rational-SRC phase tables; no hardware access."""
from pathlib import Path
import numpy as np

TAPS=64
PHASES=32


def coefficients(rate):
    offsets=np.arange(TAPS)[None,:]-(31+np.arange(PHASES+1)[:,None]/PHASES)
    cutoff=14000/rate
    table=2*cutoff*np.sinc(2*cutoff*offsets)*np.kaiser(TAPS,7.8)
    return (table/table.sum(axis=1)[:,None]).astype(np.float32)


def main():
    output=Path(__file__).resolve().parents[2]/'src/msplus/plateau/resample_coeffs.h'
    lines=['/* Generated by tools/msplus/resample_coeffs.py; readonly float32.',
           ' * 64 taps, 32 fractional phases plus endpoint, Kaiser beta 7.8.',
           ' * 14 kHz cutoff, unity DC. Linear interpolation between phases. */']
    for rate,name in [(44100,'plateau_down'),(32000,'plateau_up')]:
        lines.append(f'static const float {name}[33][64] = {{')
        for row in coefficients(rate):
            lines.append('    {'+', '.join(f'{float(value):.10e}f' for value in row)+'},')
        lines.append('};')
    output.write_text('\n'.join(lines)+'\n')


if __name__=='__main__':
    main()
